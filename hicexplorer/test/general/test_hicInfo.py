COLUMNS_LINE = "The following columns are available: ['chrom' 'start' 'end']\n"


def test_cool_metadata():
    """Default path for a cool file: everything is taken from the cooler info."""
    assert run_hicInfo(['-m', LI_COOL]) == expected_li_cool()


def test_cool_metadata_variable_bins_has_no_bin_length():
    """Li_et_al_2015.cool is bin-type 'variable' and stores bin-size 'null'.

    cooler maps that to None, so hicInfo must not print a Bin_length line.
    """
    content = run_hicInfo(['-m', LI_COOL])
    assert 'Bin_length' not in content
    assert 'Sum of matrix' not in content
    assert 'NaN bins' not in content


def test_h5():
    assert run_hicInfo(['-m', LI_H5]) == expected_li_h5()


def test_h5_ignores_no_metadata():
    """H5 always takes the slow path, so -nm must not change anything."""
    assert run_hicInfo(['-m', LI_H5, '-nm']) == expected_li_h5()


def test_cool_no_metadata():
    """-nm loads the matrix through HiCMatrix, exactly like the h5 path.

    The cool and the h5 version of Li_et_al_2015 hold the same matrix, so the
    numbers must be identical; only the trailing column line is added because
    the file is still a cooler file.
    """
    assert run_hicInfo(['-m', LI_COOL, '-nm']) == expected_li_h5(
        path=LI_COOL, columns_line=COLUMNS_LINE)


def test_100kb_cool_metadata():
    assert run_hicInfo(['-m', UNTREATED_COOL]) == expected_untreated_cool()


def test_100kb_h5():
    assert run_hicInfo(['-m', UNTREATED_H5]) == expected_untreated_h5()


def test_100kb_cool_no_metadata():
    assert run_hicInfo(['-m', UNTREATED_COOL, '-nm']) == expected_untreated_h5(
        path=UNTREATED_COOL, columns_line=COLUMNS_LINE)


def test_100kb_auxin_cool_metadata():
    assert run_hicInfo(['-m', AUXIN_COOL]) == expected_auxin_cool()


def test_100kb_auxin_cool_no_metadata():
    """The sum of the symmetric matrix differs from the 'sum' cooler attribute.

    The cooler attribute of this file is 742.3307878299139, while summing the
    lower-triangle-filled matrix gives 742.330787829914. Both are pinned on
    purpose; the difference is pure floating point summation order.
    """
    content = run_hicInfo(['-m', AUXIN_COOL, '-nm'])
    assert content == (HEADER
                       + "File:\t{}\n".format(AUXIN_COOL)
                       + "Size:\t1,972\n"
                       + "Bin_length:\t100000\n"
                       + "Sum of matrix:\t742.330787829914\n"
                       + "Chromosomes:length: chr1: 197195432 bp; \n"
                       + "Non-zero elements:\t2,931,241\n"
                       + "Minimum (non zero):\t7.890892094489899e-06\n"
                       + "Maximum:\t0.08955076886364301\n"
                       + "NaN bins:\t81\n"
                       + COLUMNS_LINE)


def test_several_matrices_outfile_keeps_only_the_last():
    """--outFileName is reopened in 'w' mode per matrix.

    With several matrices the file therefore holds only the block of the last
    matrix. This is a quirk of the 3.7.6 implementation and is pinned here so
    that the port reproduces it.
    """
    content = run_hicInfo(['-m', LI_COOL, LI_H5, UNTREATED_COOL])
    assert content == expected_untreated_cool()


def test_several_matrices_stdout(capsys):
    """-m with several matrices prints the blocks in argument order."""
    hicInfo.main(['-m', LI_COOL, LI_H5, UNTREATED_COOL])
    captured = capsys.readouterr()
    assert captured.out == (expected_li_cool() + '\n'
                            + expected_li_h5() + '\n'
                            + expected_untreated_cool() + '\n')


def test_several_matrices_mixed_no_metadata(capsys):
    hicInfo.main(['-m', UNTREATED_H5, UNTREATED_COOL, '--no_metadata'])
    captured = capsys.readouterr()
    assert captured.out == (expected_untreated_h5() + '\n'
                            + expected_untreated_h5(path=UNTREATED_COOL,
                                                    columns_line=COLUMNS_LINE)
                            + '\n')


def test_stdout(capsys):
    """Without --outFileName the same text is printed, plus print's newline."""
    hicInfo.main(['-m', UNTREATED_H5])
    captured = capsys.readouterr()
    assert captured.out == expected_untreated_h5() + '\n'


def test_stdout_two_matrices(capsys):
    hicInfo.main(['-m', UNTREATED_H5, UNTREATED_COOL])
    captured = capsys.readouterr()
    assert captured.out == (expected_untreated_h5() + '\n'
                            + expected_untreated_cool() + '\n')
