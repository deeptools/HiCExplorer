"""Characterization tests for hicInfo.

These tests pin the exact textual output of the current Python implementation
on real test matrices. They exist so that the C++ port in cpp/tools/hicInfo.cpp
can be checked against a fixed reference instead of against a moving target.

Every expected block below was produced by the 3.7.6 Python implementation and
is byte exact including tabs, the thousands separators and the two blank lines
in front of the "Generated by" block of the cooler metadata path.
"""
import warnings
warnings.simplefilter(action="ignore", category=RuntimeWarning)
warnings.simplefilter(action="ignore", category=PendingDeprecationWarning)

import os
from tempfile import NamedTemporaryFile

from hicexplorer import hicInfo
from hicexplorer._version import __version__
from hicexplorer.test.test_compute_function import compute

ROOT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                    "test_data")

LI_COOL = os.path.join(ROOT, 'Li_et_al_2015.cool')
LI_H5 = os.path.join(ROOT, 'Li_et_al_2015.h5')
DTAD = os.path.join(ROOT, 'hicDifferentialTAD')
UNTREATED_COOL = os.path.join(DTAD, 'GSM2644945_Untreated-R1.100000_chr1.cool')
UNTREATED_H5 = os.path.join(DTAD, 'GSM2644945_Untreated-R1.100000_chr1.h5')
AUXIN_COOL = os.path.join(DTAD, 'GSM2644947_Auxin2days-R1.100000_chr1.cool')

HEADER = "# Matrix information file. Created with HiCExplorer's hicInfo version {}\n".format(__version__)


def run_hicInfo(args):
    """Run hicInfo with --outFileName and return the file content."""
    outfile = NamedTemporaryFile(suffix='.txt', delete=False)
    outfile.close()
    compute(hicInfo.main, args + ['--outFileName', outfile.name], 1)
    with open(outfile.name) as file_handle:
        content = file_handle.read()
    os.unlink(outfile.name)
    return content


