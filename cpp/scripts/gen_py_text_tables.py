#!/usr/bin/env python
"""Writes two tables of hicx::pytext from the Unicode database of the reference
Python:
  cpp/core/src/py_text_nonprintable.inc  the code points that str.isprintable()
      rejects (categories Cc, Cf, Cs, Co, Cn, Zl, Zp and Zs except the space),
      as inclusive ranges; hicx::pytext::repr uses them to decide which
      characters repr(str) escapes;
  cpp/core/src/py_text_digit_zeros.inc   the code point of every decimal digit
      zero (each Nd block is ten consecutive code points 0 to 9); int() and
      float() accept these digits.

    ~/miniconda3/envs/hicx-ref-3.7.6/bin/python cpp/scripts/gen_py_text_tables.py

The output depends on the Unicode database of the interpreter (printed in the
first comment line); regenerate it only together with a move of the reference
Python.
"""
import sys
import unicodedata
from pathlib import Path

SRC = Path(__file__).resolve().parents[1] / 'core' / 'src'
OUT = SRC / 'py_text_nonprintable.inc'
OUT_DIGITS = SRC / 'py_text_digit_zeros.inc'


def main():
    ranges = []
    start = None
    for c in range(0x110001):
        bad = c < 0x110000 and not chr(c).isprintable()
        if bad and start is None:
            start = c
        elif not bad and start is not None:
            ranges.append((start, c - 1))
            start = None
    lines = ['// Generated by cpp/scripts/gen_py_text_tables.py from Python %s, Unicode %s.'
             % (sys.version.split()[0], unicodedata.unidata_version),
             '// Inclusive ranges of the code points for which str.isprintable() is false.']
    lines += ['{0x%X, 0x%X},' % r for r in ranges]
    OUT.write_text('\n'.join(lines) + '\n')
    zeros = []
    for c in range(0x110000):
        try:
            if unicodedata.decimal(chr(c)) == 0:
                zeros.append(c)
        except ValueError:
            pass
    for z in zeros:  # every block is ten consecutive digits
        assert [unicodedata.decimal(chr(z + k)) for k in range(10)] == list(range(10))
    OUT_DIGITS.write_text('// Generated by cpp/scripts/gen_py_text_tables.py from Python %s, Unicode %s.\n'
                          '// The code point of the digit zero of every decimal digit block.\n%s\n'
                          % (sys.version.split()[0], unicodedata.unidata_version,
                             '\n'.join('0x%X,' % z for z in zeros)))
    print(len(ranges), 'ranges', len(zeros), 'digit blocks', file=sys.stderr)


if __name__ == '__main__':
    main()
