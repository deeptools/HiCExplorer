#!/usr/bin/env python
"""Write the numpy/Python oracle fixtures read by cpp/tests/test_numpy_oracle.cpp.

Run with the HiCExplorer 3.7.6 reference environment (numpy 1.26.4):

    ~/miniconda3/envs/hicx-ref-3.7.6/bin/python cpp/scripts/gen_numpy_oracle_fixture.py

Every input is regenerated by the C++ test from the case line (seeded
counter-based splitmix64 stream, see Stream below), so the fixtures hold the
parameters and numpy's answer only. Families:

  sort.txt     np.argsort(kind='quicksort') and np.argpartition: FNV-1a hash of
               the returned index array.
  sum.txt      np.sum / np.add.reduce of float64 and float32 arrays, also
               through strided views: bit pattern of the result.
  repr.txt     repr(float) and str(np.float32): the string.
  arraystr.txt str(np.array(list of str)); tab separated, newlines escaped.

sort_adversary_keys.txt (input, not generated here) holds integer key arrays
that force the heapsort fall back of the introsort. They were produced by
running McIlroy's adversary ("A killer adversary for quicksort", Software:
Practice and Experience 29(4), 1999) against the hicx introsort for lengths
100, 1000, 3000 and 5000.

The argsort tie order of numpy 1.26 depends on the CPU: with AVX512_SKX it uses
x86-simd-sort, which orders equal keys differently from the portable
introsort that hicx reproduces (numpy 1.23.5 and numpy on CPUs without
AVX-512). The script therefore restarts itself with the AVX-512 features
disabled (NPY_DISABLE_CPU_FEATURES) and refuses to write the sort fixture if
numpy still reports AVX512_SKX.
"""
import os
import sys

DISABLE = ("AVX512_SKX AVX512_CLX AVX512_CNL AVX512_ICL AVX512F AVX512CD AVX512BW "
           "AVX512DQ AVX512VL AVX512VNNI AVX512IFMA AVX512VBMI AVX512VBMI2 AVX512BITALG "
           "AVX512VPOPCNTDQ")
if os.environ.get("NPY_DISABLE_CPU_FEATURES") != DISABLE:
    os.environ["NPY_DISABLE_CPU_FEATURES"] = DISABLE
    os.execv(sys.executable, [sys.executable] + sys.argv)

import numpy as np  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "fixtures",
                   "numpy_oracle")
GAMMA = np.uint64(0x9E3779B97F4A7C15)


def stream(seed, n):
    """splitmix64 outputs 1..n of the stream started at `seed`, as uint64."""
    with np.errstate(over="ignore"):
        i = np.arange(1, n + 1, dtype=np.uint64)
        z = np.uint64(seed) * GAMMA + i * GAMMA
        z = (z ^ (z >> np.uint64(30))) * np.uint64(0xBF58476D1CE4E5B9)
        z = (z ^ (z >> np.uint64(27))) * np.uint64(0x94D049BB133111EB)
        return z ^ (z >> np.uint64(31))


def unit(seed, n):
    return (stream(seed, n) >> np.uint64(11)).astype(np.float64) * 2.0 ** -53


def sort_values(mode, levels, n, seed):
    u = stream(seed, n)
    u2 = stream(seed + 1000003, n)
    if mode == 0:
        return unit(seed, n)
    if mode == 1:
        return (u % np.uint64(levels)).astype(np.float64)
    if mode == 2:
        v = (u % np.uint64(levels)).astype(np.float64)
        v[(u2 % np.uint64(7)) == 0] = np.nan
        return v
    if mode == 3:
        v = unit(seed, n)
        v[(u2 % np.uint64(3)) == 0] = 0.0
        return v
    if mode == 4:
        v = (n - np.arange(n)).astype(np.float64)
        v[(u % np.uint64(10)) == 0] = 0.0
        return v
    if mode == 5:
        i = np.arange(n)
        return np.where(i < n // 2, i, n - i).astype(np.float64)
    raise ValueError(mode)


def fnv(idx):
    h = 0xCBF29CE484222325
    for x in idx.tolist():
        for b in int(x).to_bytes(8, "little", signed=True):
            h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def write_sort():
    from numpy.core._multiarray_umath import __cpu_features__ as feat
    if feat.get("AVX512_SKX"):
        sys.exit("numpy still reports AVX512_SKX; its argsort would not be the portable one")
    lines = []
    rng = np.random.default_rng(20261030)
    sizes = [1, 2, 3, 5, 15, 16, 17, 31, 32, 33, 64, 100, 129, 500, 1000, 2047, 2048, 4096, 5000]
    seed = 1
    for n in sizes:
        for mode in range(6):
            levels = int(rng.integers(1, 25))
            v = sort_values(mode, levels, n, seed)
            lines.append(f"argsort {mode} {levels} {n} {seed} {fnv(np.argsort(v, kind='quicksort'))}")
            for k in sorted({0, n // 2, n - 1, int(rng.integers(0, n)), 3 if n > 3 else 0}):
                lines.append(f"argpartition {mode} {levels} {n} {seed} {k} "
                             f"{fnv(np.argpartition(v, k))}")
            seed += 1
    # Inputs that defeat the median-of-three pivot (found by running the
    # adversary of McIlroy, "A killer adversary for quicksort", 1999, against
    # the hicx introsort): they force the heapsort fall back. Listed
    # explicitly as integer keys.
    with open(os.path.join(OUT, "sort_adversary_keys.txt")) as handle:
        for line in handle:
            keys = np.array([float(x) for x in line.split()])
            lines.append(f"adversary {fnv(np.argsort(keys, kind='quicksort'))} " +
                         " ".join(str(int(x)) for x in keys))
    with open(os.path.join(OUT, "sort.txt"), "w") as handle:
        handle.write("\n".join(lines) + "\n")


def write_sum():
    lines = []
    seed = 100
    lengths = (list(range(0, 40)) + [63, 64, 65, 127, 128, 129, 130, 255, 256, 257, 1000, 4095,
                                     8191, 8192, 8193, 16384, 16385, 20000, 65537, 100000])
    for n in lengths:
        for mode in range(4):
            for kind in ("f64", "f32"):
                stride = 1 + (seed % 3)
                a = sum_values(mode, n, seed)
                a = a if kind == "f64" else a.astype(np.float32)
                big = np.zeros(n * stride, dtype=a.dtype)
                big[::stride] = a
                view = big[::stride]
                assert np.array_equal(view, a)
                r = np.add.reduce(view)
                assert r.tobytes() == np.sum(a).tobytes()
                bits = int(np.frombuffer(r.tobytes(), dtype=np.uint64 if kind == "f64" else np.uint32)[0])
                lines.append(f"sum {kind} {mode} {n} {seed} {bits}")
                seed += 1
    with open(os.path.join(OUT, "sum.txt"), "w") as handle:
        handle.write("\n".join(lines) + "\n")


def sum_values(mode, n, seed):
    if mode == 0:
        return unit(seed, n)
    if mode == 1:
        e = (stream(seed + 7, n) % np.uint64(33)).astype(np.int64) - 16
        return (unit(seed, n) - 0.5) * np.exp2(e.astype(np.float64))
    if mode == 2:
        return ((stream(seed, n) % np.uint64(2001)).astype(np.int64) - 1000).astype(np.float64) / 7
    return 1e8 + unit(seed, n) * 1e-3


def write_repr():
    lines = []
    for kind, dtype, ubits, nbits in (("f64", np.float64, np.uint64, 64),
                                      ("f32", np.float32, np.uint32, 32)):
        raw = stream(11 if kind == "f64" else 12, 3000)
        bits = raw if nbits == 64 else (raw >> np.uint64(32)).astype(np.uint32)
        vals = bits.view(dtype)
        dec = (((stream(13, 2000) % np.uint64(10 ** 15)).astype(np.float64) + 1) *
               10.0 ** ((stream(14, 2000) % np.uint64(50)).astype(np.float64) - 25)).astype(dtype)
        special = np.array([0.0, -0.0, np.inf, -np.inf, np.nan, 1e16, 1e15, 1e-4, 1e-5, 0.00011,
                            9999999999999998.0, 5e-324, 1.1754944e-38, 1e22, 1.0, 100.0, 0.5],
                           dtype=dtype)
        # Around the two switches to exponent form, in units of the last place.
        near = []
        for centre in (1e-4, 1e16):
            c = int(np.array([centre], dtype=dtype).view(ubits)[0])
            for d in range(-3, 4):
                near.append(np.array([c + d], dtype=ubits).view(dtype)[0])
        for v in np.concatenate([vals, dec, special, np.array(near, dtype=dtype)]):
            if np.isnan(v):
                text = "nan"
            else:
                text = repr(float(v)) if kind == "f64" else str(v)
            b = int(np.array([v], dtype=dtype).view(ubits)[0])
            lines.append(f"repr {kind} {b} {text}")
    with open(os.path.join(OUT, "repr.txt"), "w") as handle:
        handle.write("\n".join(lines) + "\n")


def write_arraystr():
    import random
    import string
    random.seed(1)
    lines = []
    for _ in range(300):
        n = random.randint(1, 30)
        items = ["".join(random.choice(string.ascii_letters + "_") for _ in range(random.randint(1, 18)))
                 for _ in range(n)]
        lines.append("\t".join(["arraystr", " ".join(items), str(np.array(items)).replace("\n", "\\n")]))
    with open(os.path.join(OUT, "arraystr.txt"), "w") as handle:
        handle.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    families = sys.argv[1:] or ["sum", "repr", "arraystr", "sort"]
    for family in families:
        globals()["write_" + family]()
