"""Writes cpp/core/src/unidecode_table.cpp from the installed Unidecode package.

hicexplorer.utilities.remove_non_ascii is unidecode.unidecode, a lookup in
per-block transliteration tables. HiCExplorer 4 carries those tables in C++
(hicx::utilities::unidecode), generated by this script from the Unidecode
version the 3.7.6 environment has, so that the lookup gives the same strings.
Unidecode is GPL-2.0-or-later, which HiCExplorer's GPL-3.0 accepts.

    python cpp/scripts/generate_unidecode_table.py [output.cpp]

Run it with the interpreter of the reference environment
(~/miniconda3/envs/__hicexplorer@3.7.6/bin/python3). The output is committed;
regenerate it only together with a move of the reference Unidecode version.
"""
import importlib
import sys
from pathlib import Path

import unidecode
from importlib.metadata import version

REPO = Path(__file__).resolve().parents[2]
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else REPO / "cpp" / "core" / "src" / "unidecode_table.cpp"

# unidecode looks at code points up to 0xeffff, block = code point >> 8.
BLOCKS = 0xeffff >> 8
blob = bytearray()
offsets = []          # per entry: start offset into the blob
block_first = []      # per block: first entry index, or -1 when there is no table
block_count = []
for block in range(BLOCKS + 1):
    try:
        mod = importlib.import_module('unidecode.x%03x' % block)
    except ImportError:
        block_first.append(-1)
        block_count.append(0)
        continue
    data = mod.data
    block_first.append(len(offsets))
    block_count.append(len(data))
    for entry in data:
        offsets.append(len(blob))
        if entry is not None:
            blob += entry.encode('utf-8')
offsets.append(len(blob))


def c_string(chunk):
    out = []
    for b in chunk:
        c = chr(b)
        if c == '"' or c == '\\':
            out.append('\\' + c)
        elif c == '?':
            out.append('\\?')  # no trigraphs
        elif 32 <= b < 127:
            out.append(c)
        else:
            out.append('\\%03o' % b)
    return ''.join(out)


lines = []
lines.append('// Generated by cpp/scripts/generate_unidecode_table.py from Unidecode %s.' % version('Unidecode'))
lines.append('// Do not edit. The transliteration tables are Unidecode\'s (GPL-2.0-or-later).')
lines.append('#include <cstdint>')
lines.append('')
lines.append('namespace hicx::utilities::unidecode_table {')
lines.append('')
lines.append('extern const char kBlob[];')
lines.append('extern const std::uint32_t kOffsets[];')
lines.append('extern const std::int32_t kBlockFirst[];')
lines.append('extern const std::uint16_t kBlockCount[];')
lines.append('extern const int kBlocks;')
lines.append('')
lines.append('const int kBlocks = %d;' % (BLOCKS + 1))
lines.append('')
lines.append('const char kBlob[] =')
step = 96
for i in range(0, len(blob), step):
    lines.append('    "%s"' % c_string(blob[i:i + step]))
if not blob:
    lines.append('    ""')
lines[-1] += ';'
lines.append('')
lines.append('const std::uint32_t kOffsets[] = {')
for i in range(0, len(offsets), 12):
    lines.append('    ' + ', '.join(str(x) for x in offsets[i:i + 12]) + ',')
lines.append('};')
lines.append('')
lines.append('const std::int32_t kBlockFirst[] = {')
for i in range(0, len(block_first), 16):
    lines.append('    ' + ', '.join(str(x) for x in block_first[i:i + 16]) + ',')
lines.append('};')
lines.append('')
lines.append('const std::uint16_t kBlockCount[] = {')
for i in range(0, len(block_count), 16):
    lines.append('    ' + ', '.join(str(x) for x in block_count[i:i + 16]) + ',')
lines.append('};')
lines.append('')
lines.append('}  // namespace hicx::utilities::unidecode_table')
OUT.write_text('\n'.join(lines) + '\n')
print('%s: %d entries, %d bytes of text' % (OUT, len(offsets) - 1, len(blob)))
