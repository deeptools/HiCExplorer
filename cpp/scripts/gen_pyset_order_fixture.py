#!/usr/bin/env python
"""Writes cpp/tests/fixtures/cpython/set_order.txt, the oracle of hicx/py_set_order.hpp.

Every case is a sequence of operations on a Python set of ints or of tuples of
ints, followed by the iteration order of the resulting set, as the real
interpreter produces it. Run it with the interpreter whose behaviour is
reproduced:

    ~/miniconda3/envs/hicx-ref-3.7.6/bin/python cpp/scripts/gen_pyset_order_fixture.py

Reference interpreter: Python 3.12.7 (the Python of the HiCExplorer 3.7.6
reference environment, cpp/reference_env/pins.txt). The fixture records the
version on its first line.

Format, one token per whitespace:
  version <python version>
  case <name> <kind>             kind: i (int), t2 (pair), t3 (triple)
  a <key>                        s.add
  d <key>                        s.discard
  u <n> <key>*n                  s.update(list)
  U <n> <key>*n                  s.update(set(list))
  x <n> <key>*n                  s.difference_update(set(list))
  c                              s = set(s)
  order <n> <key>*n              the iteration order afterwards
  bulk <name> <kind> <seed> <count> <digest>
                                 large case generated by splitmix64 from the
                                 seed (see bulk_keys / bulk_run below), the
                                 order summarised by an FNV-1a digest
A pair key is written as two integers, a triple as three.
"""
import random
import sys

MASK64 = (1 << 64) - 1


def splitmix(state):
    state = (state + 0x9E3779B97F4A7C15) & MASK64
    z = state
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK64
    return state, z ^ (z >> 31)


def signed(x):
    return x - (1 << 64) if x >= (1 << 63) else x


def bulk_keys(kind, seed, count):
    state = seed
    keys = []
    for _ in range(count):
        state, x = splitmix(state)
        if kind == 'i':
            # a mix of small, medium and full-width values of both signs
            sel = x & 3
            if sel == 0:
                keys.append(signed(x))
            elif sel == 1:
                keys.append((x >> 2) % (4 * count))
            elif sel == 2:
                keys.append(-((x >> 2) % (4 * count)) - 1)
            else:
                keys.append(((x >> 2) % (1 << 40)) << 21)
        elif kind == 't2':
            keys.append(((x >> 8) % 100003 - 50000, (x >> 40) % 777))
        else:
            keys.append(((x >> 8) % 1009 - 500, (x >> 24) % 211, (x >> 40) % 61 - 30))
    return keys


def bulk_run(kind, seed, count):
    keys = bulk_keys(kind, seed, count)
    s = set()
    for k in keys:
        s.add(k)
    for j, k in enumerate(keys):
        if j % 3 == 0:
            s.discard(k)
    for j, k in enumerate(keys):
        if j % 5 == 0:
            s.add(k)
    other = set(keys[::7])
    s.update(other)
    s.difference_update(set(keys[::11]))
    return s


def digest(order):
    h = 0xCBF29CE484222325
    for key in order:
        parts = key if isinstance(key, tuple) else (key,)
        for p in parts:
            for byte in (p & MASK64).to_bytes(8, 'little'):
                h = ((h ^ byte) * 0x100000001B3) & MASK64
    return h


def fmt(key):
    return ' '.join(str(p) for p in (key if isinstance(key, tuple) else (key,)))


def random_key(rng, kind, span, wide):
    def one():
        r = rng.random()
        if wide and r < 0.15:
            return rng.randint(-(1 << 63), (1 << 63) - 1)
        if wide and r < 0.3:
            return rng.randint(-(1 << 62), 1 << 62) << rng.randint(0, 1)
        return rng.randint(-span, span)
    if kind == 'i':
        return one()
    return tuple(one() for _ in range(2 if kind == 't2' else 3))


def make_case(rng, name, kind, nops, span, wide, discard_bias):
    lines = ['case %s %s' % (name, kind)]
    s = set()
    pool = []

    def pick():
        if pool and rng.random() < 0.5:
            return rng.choice(pool)
        k = random_key(rng, kind, span, wide)
        pool.append(k)
        return k

    for _ in range(nops):
        r = rng.random()
        if r < 0.55 - discard_bias:
            k = pick()
            s.add(k)
            lines.append('a ' + fmt(k))
        elif r < 0.55:
            k = pick()
            s.discard(k)
            lines.append('d ' + fmt(k))
        elif r < 0.65:
            ks = [pick() for _ in range(rng.randint(0, 40))]
            s.update(ks)
            lines.append('u %d %s' % (len(ks), ' '.join(fmt(k) for k in ks)))
        elif r < 0.77:
            ks = [pick() for _ in range(rng.randint(0, 60))]
            s.update(set(ks))
            lines.append('U %d %s' % (len(ks), ' '.join(fmt(k) for k in ks)))
        elif r < 0.93:
            if rng.random() < 0.6 and s:
                ks = rng.sample(sorted(s), min(len(s), rng.randint(0, 40)))
            else:
                ks = [pick() for _ in range(rng.randint(0, 40))]
            s.difference_update(set(ks))
            lines.append('x %d %s' % (len(ks), ' '.join(fmt(k) for k in ks)))
        else:
            s = set(s)
            lines.append('c')
    order = list(s)
    lines.append('order %d %s' % (len(order), ' '.join(fmt(k) for k in order)))
    return lines


def main():
    out = ['version ' + sys.version.split()[0]]
    rng = random.Random(20261030)
    n = 0
    for kind in ('i', 't2', 't3'):
        for nops, span, wide, bias in ((5, 20, False, 0.0), (30, 40, False, 0.1),
                                       (200, 100, False, 0.2), (400, 5000, True, 0.2),
                                       (1500, 300, False, 0.3), (2500, 1 << 20, True, 0.1)):
            for rep in range(6 if nops <= 400 else 1):
                n += 1
                out += make_case(rng, 'rand%d' % n, kind, nops, span, wide, bias)
    # consecutive and strided integers, the way bin indices come
    for name, keys in (('ascending', list(range(300))), ('descending', list(range(300, 0, -1))),
                       ('stride8', list(range(0, 800, 8))), ('stride2e', [i << 10 for i in range(200)]),
                       ('negatives', [-i for i in range(1, 200)]),
                       ('minus_one_two', [-1, -2, 0, 1, 2, -3]),
                       ('bounds', [(1 << 63) - 1, -(1 << 63), (1 << 61) - 1, (1 << 61), -(1 << 61), 0])):
        out.append('case %s i' % name)
        out += ['a %d' % k for k in keys]
        out.append('order %d %s' % (len(set(keys)), ' '.join(str(k) for k in list(set(keys)))))
    for kind, seed, count in (('i', 1, 1000), ('i', 2, 100000), ('i', 3, 1000000),
                              ('t2', 4, 200000), ('t2', 5, 1000000), ('t3', 6, 50000)):
        out.append('bulk b%d %s %d %d %d' % (seed, kind, seed, count,
                                              digest(list(bulk_run(kind, seed, count)))))
    print('\n'.join(out))


if __name__ == '__main__':
    main()
