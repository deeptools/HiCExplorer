#!/usr/bin/env python3
"""Writes recipe/recipe.yaml (rattler-build) from pins.txt.

pins.txt has one line per package: `name version build` (the first three
columns of `conda list`, channel dropped). The generated metapackage depends
on every line with an exact version and build string, so a solve can only
return the reference environment. Regenerate after editing pins.txt:

    python3 make_recipe.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
VERSION = "3.7.6.1"


def main():
    pins = []
    for line in (HERE / "pins.txt").read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            name, version, build = line.split()[:3]
            pins.append((name, version, build))
    pins.sort()
    out = [
        "# Generated by ../make_recipe.py from ../pins.txt; do not edit by hand.",
        "context:",
        f"  version: \"{VERSION}\"",
        "",
        "package:",
        "  name: hicexplorer-equivalence-reference",
        "  version: ${{ version }}",
        "",
        "build:",
        "  number: 0",
        "  noarch: generic",
        "",
        "requirements:",
        "  run:",
    ]
    out += [f"    - {n} =={v} {b}" for n, v, b in pins]
    out += [
        "",
        "about:",
        "  homepage: https://github.com/deeptools/HiCExplorer",
        "  license: GPL-3.0-or-later",
        "  summary: Pinned dependency set of the HiCExplorer 3.7.6 equivalence reference",
        "  description: |",
        "    Metapackage with no files. It pins, to exact version and build,",
        "    every package of the conda environment in which the HiCExplorer 3.7.6",
        "    reference runs and in which the equivalence tests are executed.",
        "    Install with the channels conda-forge and bioconda.",
        "",
    ]
    (HERE / "recipe" / "recipe.yaml").write_text("\n".join(out))
    print(f"{len(pins)} pins")


if __name__ == "__main__":
    main()
